import { createTool } from "@mastra/core/tools";
import { z } from "zod";
import { ChatServiceError } from "../../common/errors";
import { SlugSchema } from "../../dto/library";
import { getAssetStorage, type AssetStorage } from "../../services/assetStorage";
import { getProjectState } from "./projectTools";
import { requireCurrentProject } from "./requestContext";

/**
 * 参考图身份识别回路（免费）：本产品无文生图，所有模型都先有参考图再生成，
 * 因此参考图天然覆盖绝大多数资产（CAD/wildcard 例外，无源图）。当用户用外观
 * 描述而非名字指代资产、文本名录（system 消息里的「资产」列表，按创建时间
 * 新→旧排列）匹配不上时，用这个工具代替瞎猜 slug：候选 slug 由 agent 自己
 * 从名录/对话上下文里挑（优先最近创建/最近提到的几个），工具只做存在性与
 * 「有没有参考图」校验，不做筛选决策——避免和 app 侧的解析逻辑产生两份真相。
 * 与 inspect-asset 同款异步：本轮不返回图片，候选参考图随后经请求的 `resume`
 * 字段交回（OpenAI 兼容协议的 tool 消息装不了图）。但比 inspect-asset 简单：
 * 参考图已经在磁盘上，app 不需要开视口渲染，直接读库交回即可。
 */

const MAX_CANDIDATES = 5;

export interface IdentifyCandidatesResult {
  assetSlugs: string[];
  skipped?: string[];
}

/** 核心校验：候选 slug 必须存在且有参考图，不做筛选决策（见头注） */
export async function resolveIdentifyCandidates(
  storage: AssetStorage,
  projectSlug: string,
  assetSlugs: string[],
): Promise<IdentifyCandidatesResult> {
  const state = await getProjectState(storage, projectSlug);
  const bySlug = new Map(state.assets.map((asset) => [asset.slug, asset]));

  const missing: string[] = [];
  const noReferenceImage: string[] = [];
  const resolved: string[] = [];
  for (const slug of assetSlugs) {
    const asset = bySlug.get(slug);
    if (!asset) {
      missing.push(slug);
      continue;
    }
    if (!asset.identity || asset.identity.sourceImages.length === 0) {
      noReferenceImage.push(slug);
      continue;
    }
    resolved.push(slug);
  }

  if (missing.length > 0) {
    throw new ChatServiceError(`Asset not found: ${missing.join(", ")}`, 404, "asset_not_found");
  }
  if (resolved.length === 0) {
    throw new ChatServiceError(
      `The following assets have no reference image (assets generated by CAD or the escape hatch have no source image): ${noReferenceImage.join(", ")}; ` +
        "cannot confirm identity from a reference image, use inspect-asset instead or ask the user directly",
      409,
      "no_reference_image",
    );
  }

  return {
    assetSlugs: resolved,
    ...(noReferenceImage.length > 0 ? { skipped: noReferenceImage } : {}),
  };
}

export const identifyAssetTool = createTool({
  id: "identify-asset",
  description:
    `Confirm which asset the user means (free): call this when the user refers to an asset by appearance/color/shape ` +
    `rather than by name and you therefore cannot determine the slug from the current asset roster (already sorted by creation time, ` +
    `newest → oldest); do not act directly on a guessed ` +
    `slug. Pass the candidate assetSlugs you suspect (if unsure, prefer those nearest the top of the roster, i.e. the most recently ` +
    `created, at most ${MAX_CANDIDATES}). Note: this turn returns no images — the workbench will hand back each ` +
    `candidate asset's reference image (labeled with its slug) directly afterwards; use them to confirm identity, then continue the operation you originally intended.`,
  inputSchema: z.object({
    assetSlugs: z.array(SlugSchema).min(1).max(MAX_CANDIDATES),
  }),
  execute: async (input, context) => {
    const projectSlug = requireCurrentProject(context);
    const storage = getAssetStorage();
    const result = await resolveIdentifyCandidates(storage, projectSlug, input.assetSlugs);
    return {
      requested: true,
      ...result,
      note: "Reference images requested. Each candidate asset's reference image (one per candidate asset, labeled with its slug) will be handed back directly afterwards; use them to confirm identity, then continue the operation you originally intended.",
    };
  },
});
